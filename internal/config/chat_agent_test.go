func chatAgentFixture(t *testing.T, bind, tokenRef string) string {
	t.Helper()
	dir := t.TempDir()
	doc := "config_version: " + itoa(TargetConfigVersion) + "\nagent:\n  id: " + testAgentID + "\nllm:\n  default: p::m\nchannels:\n  zmqcli:\n    enabled: true\n    bind: " + bind + "\n    auth_token: " + tokenRef + "\n"
	if err := os.WriteFile(filepath.Join(dir, ConfigFileName), []byte(doc), 0o600); err != nil {
		t.Fatal(err)
	}

	return dir
}

func itoa(n int) string { return strconv.Itoa(n) }

func storeSecret(t *testing.T, dir, name, value string) {
	t.Helper()
	s, err := secretstore.New(secretstore.Options{Dir: dir, Key: secretstore.KeySpec{Location: secretstore.KeyAgentDir}, AgentID: testAgentID, Log: zerolog.Nop()})
	if err != nil {
		t.Fatal(err)
	}
	if err = s.Update(t.Context(), func(p *secretstore.Payload) error {
		p.Secrets[name] = secretstore.Secret{Value: value}

		return nil
	}); err != nil {
		t.Fatal(err)
	}
}

func snapshotDir(t *testing.T, dir string) map[string]int64 {
	t.Helper()
	out := map[string]int64{}
	_ = filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			fi, _ := d.Info()
			out[p] = fi.Size()<<20 | int64(fi.ModTime().Nanosecond()%1_000_000)
		}

		return nil
	})

	return out
}

func TestResolveChatAgentReadsTheStoreAndMapsAWildcardBind(t *testing.T) {
	dir := chatAgentFixture(t, "tcp://0.0.0.0:7700", "!secret zmqcli_auth_token")
	secret := strings.Repeat("c", 40)
	storeSecret(t, dir, "zmqcli_auth_token", secret)
	before := snapshotDir(t, dir)

	got, err := ResolveChatAgent(t.Context(), dir)
	if err != nil {
		t.Fatal(err)
	}
	if got.Token != secret || got.Address != "tcp://127.0.0.1:7700" {
		t.Fatalf("resolved = %+v", got)
	}
	after := snapshotDir(t, dir)
	if len(after) != len(before) {
		t.Fatalf("chat created files under the agent: before=%v after=%v", before, after)
	}
	for p, v := range before {
		if after[p] != v {
			t.Fatalf("chat modified %s", p)
		}
	}
}

func TestResolveChatAgentFailuresAreSingleLinesNamingTheMissingPiece(t *testing.T) {
	// No store yet: the secret is generated by the first serve.
	dir := chatAgentFixture(t, "tcp://127.0.0.1:7600", "!secret zmqcli_auth_token")
	if _, err := ResolveChatAgent(t.Context(), dir); err == nil || !strings.Contains(err.Error(), "ready serve") || strings.Contains(err.Error(), "\n") {
		t.Fatalf("missing store = %v", err)
	}
	// A short value behaves as pending.
	storeSecret(t, dir, "zmqcli_auth_token", "short")
	if _, err := ResolveChatAgent(t.Context(), dir); err == nil {
		t.Fatal("a non-conforming secret was accepted")
	}
	// An external file reference.
	ext := filepath.Join(t.TempDir(), "tok")
	_ = os.WriteFile(ext, []byte(strings.Repeat("e", 40)+"\n"), 0o600)
	dir2 := chatAgentFixture(t, "tcp://127.0.0.1:7600", "!secret_file "+ext)
	if got, err := ResolveChatAgent(t.Context(), dir2); err != nil || got.Token != strings.Repeat("e", 40) {
		t.Fatalf("external file = %+v, %v", got, err)
	}
	// An older schema is refused with guidance.
	old := t.TempDir()
	_ = os.WriteFile(filepath.Join(old, ConfigFileName), []byte("config_version: 2\nllm: {}\n"), 0o600)
	if TargetConfigVersion != 1 {
		if _, err := ResolveChatAgent(t.Context(), old); err == nil || !strings.Contains(err.Error(), "--token-file") {
			t.Fatalf("old schema = %v", err)
		}
	}
}
