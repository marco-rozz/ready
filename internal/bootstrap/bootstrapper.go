// Package bootstrap manages per-session preloading of core skills for each channel.
// It owns the agentskills session lifecycle, the static shell cache, and the
// dynamic handler registry.
package bootstrap

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"

	agentskillsSpec "github.com/flexigpt/agentskills-go/runtime/spec"
	"github.com/marco-rozz/ready/internal/skills"
	"github.com/rs/zerolog"
)

// HandlerIDDeviceList is the well-known handler ID for the Home Assistant
// device list dynamic handler. Use this constant when registering the handler
// and when referencing it in asset frontmatter.
const HandlerIDDeviceList = "ha-device-list"

// ErrSessionNotFound is returned when StaticShell is called before
// GetOrCreateSession for the same chatKey.
var ErrSessionNotFound = errors.New("bootstrap: session not found (call GetOrCreateSession first)")

// DynamicHandler generates markdown content that is injected into the prompt
// on every LLM turn. Implementations must read from in-memory state only —
// no synchronous API calls are allowed inside Generate.
type DynamicHandler interface {
	Generate(ctx context.Context) (string, error)
}

// ContentLoader loads file content by absolute path, typically with caching
// and fsnotify-based invalidation. skillcache.SkillCache satisfies this.
type ContentLoader interface {
	Load(ctx context.Context, path string) (string, error)
}

// skillsManager is the subset of skills.Manager used by the Bootstrapper.
type skillsManager interface {
	NewSession(ctx context.Context) (agentskillsSpec.SessionID, error)
	CloseSession(ctx context.Context, sid agentskillsSpec.SessionID) error
	LoadSkill(ctx context.Context, sessionID agentskillsSpec.SessionID, skillName string) (string, error)
	GetMetadataPrompt(ctx context.Context, sessionID agentskillsSpec.SessionID) (string, error)
	GetSkillLocation(skillName string) (string, error)
}

var _ skillsManager = (*skills.Manager)(nil)

// dynamicPointer records a file whose content is generated by a handler at turn time.
type dynamicPointer struct {
	handlerID string
}

// sessionState holds runtime state for one chat session.
type sessionState struct {
	agentSkillsSID  agentskillsSpec.SessionID
	channelName     string           // the channel that owns this session
	dynamicPointers []dynamicPointer // collected during static walk
}

// Bootstrapper owns per-chat session lifecycle, static shell cache, and
// the dynamic handler registry.
type Bootstrapper struct {
	mu           sync.RWMutex
	sessions     map[string]*sessionState // chatKey → state
	staticCache  map[string]string        // chatKey → combined static shell
	handlers     map[string]DynamicHandler
	bootstrapCfg map[string][]string // channelName → []skillName
	skillsMgr    skillsManager
	loader       ContentLoader
	logger       zerolog.Logger
}

// New creates a Bootstrapper. bootstrapCfg maps each channel name to the list
// of skill names that should be preloaded for every session on that channel.
// loader is used to read file content with caching/invalidation support;
// pass skillcache.SkillCache in production.
func New(skillsMgr skillsManager, loader ContentLoader, bootstrapCfg map[string][]string, logger zerolog.Logger) *Bootstrapper {
	b := &Bootstrapper{
		sessions:     make(map[string]*sessionState),
		staticCache:  make(map[string]string),
		handlers:     make(map[string]DynamicHandler),
		bootstrapCfg: bootstrapCfg,
		skillsMgr:    skillsMgr,
		loader:       loader,
		logger:       logger.With().Str("component", "bootstrap").Logger(),
	}

	// Register built-in placeholder handlers.
	b.handlers[HandlerIDDeviceList] = &noopHandler{}

	return b
}

// RegisterHandler adds or replaces a DynamicHandler for the given handler ID.
func (b *Bootstrapper) RegisterHandler(id string, h DynamicHandler) {
	b.mu.Lock()
	b.handlers[id] = h
	b.mu.Unlock()
}

// GetOrCreateSession returns the agentskills session ID for a conversation
// Session (chatKey is the Session ID — session-lifecycle D7), creating it
// (and running the bootstrap sequence) on the first call.
func (b *Bootstrapper) GetOrCreateSession(ctx context.Context, chatKey, channelName string) (agentskillsSpec.SessionID, error) {
	b.mu.RLock()
	if s, ok := b.sessions[chatKey]; ok {
		b.mu.RUnlock()

		return s.agentSkillsSID, nil
	}
	b.mu.RUnlock()

	sid, err := b.skillsMgr.NewSession(ctx)
	if err != nil {
		return "", fmt.Errorf("failed to create agentskills session for %q: %w", chatKey, err)
	}

	for _, skillName := range b.bootstrapCfg[channelName] {
		if _, loadErr := b.skillsMgr.LoadSkill(ctx, sid, skillName); loadErr != nil {
			b.logger.Warn().
				Str("chat", chatKey).
				Str("skill", skillName).
				Err(loadErr).
				Msg("bootstrap: failed to load skill into session")
		}
	}

	state := &sessionState{agentSkillsSID: sid, channelName: channelName}

	b.mu.Lock()
	// Double-check: another goroutine may have created the session while we
	// were doing I/O outside the lock. If so, discard the newly created session
	// and return the existing one to avoid a session leak.
	if existing, ok := b.sessions[chatKey]; ok {
		b.mu.Unlock()
		// Close the duplicated session we just created (best-effort).
		_ = b.skillsMgr.CloseSession(ctx, sid)

		return existing.agentSkillsSID, nil
	}
	b.sessions[chatKey] = state
	b.mu.Unlock()

	b.logger.Debug().
		Str("chat", chatKey).
		Str("channel", channelName).
		Strs("skills", b.bootstrapCfg[channelName]).
		Msg("bootstrap: session created")

	return sid, nil
}

// StaticShell returns the cached static shell for chatKey, building it from
// disk on a cache miss.  The shell includes the SKILL.md and all non-dynamic
// .md assets for every bootstrapped skill on the chat's channel.
//
// Returns ErrSessionNotFound if GetOrCreateSession has not been called first.
func (b *Bootstrapper) StaticShell(ctx context.Context, chatKey, channelName string) (string, error) {
	b.mu.RLock()
	if cached, ok := b.staticCache[chatKey]; ok {
		b.mu.RUnlock()

		return cached, nil
	}
	// Verify session exists while we hold the read lock.
	_, sessionExists := b.sessions[chatKey]
	b.mu.RUnlock()

	if !sessionExists {
		return "", ErrSessionNotFound
	}

	var sb strings.Builder
	var pointers []dynamicPointer

	skillNames := b.bootstrapCfg[channelName]
	if len(skillNames) > 0 {
		sb.WriteString("## Preloaded Skills (already in context — do NOT use skills-load for these)\n")
		sb.WriteString("The following skills are already fully loaded and ready to use: ")
		sb.WriteString(strings.Join(skillNames, ", "))
		sb.WriteString(".\nApply them directly when relevant. Do NOT call skills-load for them.\n\n")
	}

	for _, skillName := range skillNames {
		loc, err := b.skillsMgr.GetSkillLocation(skillName)
		if err != nil {
			b.logger.Warn().Str("skill", skillName).Err(err).Msg("bootstrap: skill location not found, skipping")

			continue
		}

		// Read the primary SKILL.md via the content loader (cached + fsnotify).
		skillMD := filepath.Join(loc, "SKILL.md")
		if content, readErr := b.loader.Load(ctx, skillMD); readErr == nil {
			sb.WriteString(content)
			sb.WriteString("\n\n")
		} else {
			b.logger.Warn().Str("file", skillMD).Err(readErr).Msg("bootstrap: failed to read SKILL.md")
		}

		// Walk the skill directory for additional assets.
		pts, walkErr := b.walkAssets(ctx, loc, &sb)
		if walkErr != nil {
			b.logger.Warn().Str("skill", skillName).Err(walkErr).Msg("bootstrap: asset walk failed")
		}

		pointers = append(pointers, pts...)
	}

	shell := sb.String()

	b.mu.Lock()
	// Double-check: another goroutine may have populated the cache while we
	// were doing disk I/O. Use the first writer's result to stay consistent.
	if cached, ok := b.staticCache[chatKey]; ok {
		b.mu.Unlock()

		return cached, nil
	}
	b.staticCache[chatKey] = shell
	if s, ok := b.sessions[chatKey]; ok {
		s.dynamicPointers = pointers
	}
	b.mu.Unlock()

	return shell, nil
}

// DynamicContent calls all registered dynamic handlers whose IDs were
// discovered during the static walk for chatKey, concatenates non-empty
// results, and returns the combined markdown string.  Returns "" when all
// handlers produce no content.
func (b *Bootstrapper) DynamicContent(ctx context.Context, chatKey string) string {
	b.mu.RLock()
	state, ok := b.sessions[chatKey]
	if !ok {
		b.mu.RUnlock()

		return ""
	}
	ptrs := make([]dynamicPointer, len(state.dynamicPointers))
	copy(ptrs, state.dynamicPointers)

	b.mu.RUnlock()

	var sb strings.Builder

	for _, ptr := range ptrs {
		b.mu.RLock()
		h, found := b.handlers[ptr.handlerID]
		b.mu.RUnlock()

		if !found {
			b.logger.Warn().Str("handler", ptr.handlerID).Msg("bootstrap: dynamic handler not registered")

			continue
		}

		// Guard against the trap where an asset declares source:dynamic with a
		// handler ID that only resolves to the built-in placeholder: no real
		// handler was ever wired, so the dynamic content would be silently
		// empty. Warn instead of failing silently.
		if _, isNoop := h.(*noopHandler); isNoop {
			b.logger.Warn().
				Str("handler", ptr.handlerID).
				Msg("bootstrap: dynamic handler is the placeholder noop — no real handler registered, dynamic content will be empty")

			continue
		}

		content, err := h.Generate(ctx)
		if err != nil {
			b.logger.Warn().Str("handler", ptr.handlerID).Err(err).Msg("bootstrap: dynamic handler error")

			continue
		}

		if content != "" {
			sb.WriteString(content)
			sb.WriteString("\n\n")
		}
	}

	return strings.TrimRight(sb.String(), "\n")
}

// Invalidate clears the static shell cache only for sessions whose channel
// uses skillName as a bootstrap skill.  No-op if skillName is not bootstrapped
// anywhere.
func (b *Bootstrapper) Invalidate(skillName string) {
	// Collect channels that bootstrap this skill.
	affectedChannels := make(map[string]struct{})
	for ch, skills := range b.bootstrapCfg {
		for _, s := range skills {
			if s == skillName {
				affectedChannels[ch] = struct{}{}

				break
			}
		}
	}

	if len(affectedChannels) == 0 {
		return
	}

	b.mu.Lock()
	for chatKey, state := range b.sessions {
		if _, affected := affectedChannels[state.channelName]; affected {
			delete(b.staticCache, chatKey)
		}
	}
	b.mu.Unlock()

	b.logger.Debug().Str("skill", skillName).Msg("bootstrap: static cache invalidated for affected sessions")
}

// Evict clears the cached CONTENT for an absolute file path by delegating to
// the loader's cache eviction when it supports one (skillcache.SkillCache in
// production). criticalities-remediation (H8): the home-topology generated
// assets are written directly by the twin Snapshotter, which calls this via
// the twin.SkillInvalidator interface — without it the content cache keeps
// serving the bytes read at first bootstrap forever (the filesystem watcher
// intentionally skips generated files).
func (b *Bootstrapper) Evict(path string) {
	if evictor, ok := b.loader.(interface{ Evict(string) }); ok {
		evictor.Evict(path)
		b.logger.Debug().Str("path", path).Msg("bootstrap: content cache evicted")

		return
	}

	b.logger.Debug().Str("path", path).Msg("bootstrap: loader has no content-cache eviction — nothing to evict")
}

// Close closes the agentskills session bound to key (a conversation Session
// ID — session-lifecycle D7) and drops its cached static shell. The next
// GetOrCreateSession for a new Session runs the bootstrap sequence afresh.
// Closing an unknown key is a no-op.
func (b *Bootstrapper) Close(ctx context.Context, key string) error {
	b.mu.Lock()
	state, ok := b.sessions[key]
	delete(b.sessions, key)
	delete(b.staticCache, key)
	b.mu.Unlock()

	if !ok {
		return nil
	}

	if err := b.skillsMgr.CloseSession(ctx, state.agentSkillsSID); err != nil {
		return fmt.Errorf("failed to close agentskills session for %q: %w", key, err)
	}

	return nil
}

// CloseAll closes every agentskills session and clears all internal maps.
// Should be called during graceful shutdown.
func (b *Bootstrapper) CloseAll(ctx context.Context) error {
	b.mu.Lock()
	sessions := make(map[string]*sessionState, len(b.sessions))
	for k, v := range b.sessions {
		sessions[k] = v
	}
	clear(b.sessions)
	clear(b.staticCache)
	b.mu.Unlock()

	var errs []string

	for chatKey, state := range sessions {
		if err := b.skillsMgr.CloseSession(ctx, state.agentSkillsSID); err != nil {
			errs = append(errs, fmt.Sprintf("chat %q: %v", chatKey, err))
		}
	}

	if len(errs) > 0 {
		return fmt.Errorf("bootstrap CloseAll errors: %s", strings.Join(errs, "; "))
	}

	return nil
}

// walkAssets recursively walks the skill directory, appending static asset
// content to sb and returning dynamic pointers for files marked source:dynamic.
// SKILL.md at the root is skipped (already read by the caller).
func (b *Bootstrapper) walkAssets(ctx context.Context, skillDir string, sb *strings.Builder) ([]dynamicPointer, error) {
	var pointers []dynamicPointer

	err := filepath.WalkDir(skillDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() {
			return nil
		}

		if !strings.HasSuffix(path, ".md") {
			return nil
		}

		// Skip the root SKILL.md — already read by the caller.
		if filepath.Base(path) == "SKILL.md" && filepath.Dir(path) == skillDir {
			return nil
		}

		isDynamic, handlerID, isIgnored, parseErr := parseFrontmatter(path)
		if parseErr != nil {
			b.logger.Warn().Str("file", path).Err(parseErr).Msg("bootstrap: frontmatter parse error")
		}

		if isIgnored {
			return nil
		}

		if isDynamic {
			pointers = append(pointers, dynamicPointer{handlerID: handlerID})

			return nil
		}

		content, readErr := b.loader.Load(ctx, path)
		if readErr != nil {
			b.logger.Warn().Str("file", path).Err(readErr).Msg("bootstrap: failed to read asset")

			return nil
		}

		sb.WriteString(content)
		sb.WriteString("\n\n")

		return nil
	})

	return pointers, err
}

// parseFrontmatter reads the YAML-like frontmatter block (delimited by ---)
// at the top of an .md file and returns whether the asset is dynamic, its
// handler ID, and whether the asset should be excluded from the static shell
// (inject: false or ignored: true).  Returns an error if the opening delimiter
// is found but the closing delimiter is missing (truncated file).
func parseFrontmatter(path string) (isDynamic bool, handlerID string, isIgnored bool, err error) {
	f, err := os.Open(path)
	if err != nil {
		return false, "", false, err
	}
	defer f.Close()

	scanner := bufio.NewScanner(f)

	// First non-empty line must be "---" to start a frontmatter block.
	if !scanner.Scan() {
		return false, "", false, nil
	}

	if strings.TrimSpace(scanner.Text()) != "---" {
		return false, "", false, nil
	}

	closed := false

	for scanner.Scan() {
		line := scanner.Text()
		if strings.TrimSpace(line) == "---" {
			closed = true

			break
		}

		key, value, found := strings.Cut(line, ":")
		if !found {
			continue
		}

		switch strings.TrimSpace(key) {
		case "source":
			if strings.TrimSpace(value) == "dynamic" {
				isDynamic = true
			}
		case "handler":
			handlerID = strings.TrimSpace(value)
		case "inject":
			if strings.TrimSpace(value) == "false" {
				isIgnored = true
			}
		case "ignored":
			if strings.TrimSpace(value) == "true" {
				isIgnored = true
			}
		}
	}

	if scanErr := scanner.Err(); scanErr != nil {
		return isDynamic, handlerID, isIgnored, scanErr
	}

	if !closed {
		return false, "", false, fmt.Errorf("unclosed frontmatter block in %s", path)
	}

	return isDynamic, handlerID, isIgnored, nil
}

// noopHandler is a placeholder that always returns empty content.
type noopHandler struct{}

func (n *noopHandler) Generate(_ context.Context) (string, error) {
	return "", nil
}
